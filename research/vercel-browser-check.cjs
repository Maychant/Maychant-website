const { chromium } = require('/private/tmp/maychant-visual-review/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const out = path.join(__dirname, 'qa-neighborhood/vercel');
  fs.mkdirSync(out, { recursive: true });
  await page.goto(process.env.MAYCHANT_CHECK_URL || 'http://localhost:5176', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('#waitlist-form')?.dataset.ready === 'true');
  await page.waitForTimeout(1800);
  await page.screenshot({ path: path.join(out, 'desktop.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('[data-audience-select="seller"]').click();
  assert.equal(await page.locator('[data-audience-select="seller"]').getAttribute('aria-expanded'), 'true');
  assert.equal(await page.locator('[data-audience-select="buyer"]').getAttribute('aria-expanded'), 'false');
  await page.locator('[data-chapter="knowledge"][aria-controls]').click();
  assert.equal(await page.locator('#chapter-tab-knowledge').getAttribute('aria-expanded'), 'true');
  await page.locator('.seller-cta').click();
  assert.equal(await page.locator('#waitlist-dialog').evaluate(e => e.open), true);
  assert.equal(await page.locator('input[name="role"]:checked').inputValue(), 'seller');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#waitlist-dialog').evaluate(e => e.open), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(out, 'mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.buyer-cta').click();
  assert.equal(await page.locator('input[name="role"]:checked').inputValue(), 'buyer');
  await page.locator('#waitlist-name').fill('Synthetic Browser Check');
  await page.locator('#waitlist-email').fill('synthetic@example.invalid');
  await page.locator('[name="consent"]').check();
  await page.route('**/api/waitlist', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ok:false,error:'Synthetic unavailable response'}) }));
  await page.locator('.submit-button').click();
  await page.getByText('Synthetic unavailable response').waitFor();
  assert.equal(await page.locator('#waitlist-form').isVisible(), true);
  await page.screenshot({ path: path.join(out, 'mobile-modal.png') });
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: desktop/mobile layout, scripts, buyer/seller expansion, chapter accordion, popup role selection, Escape, and failed-save feedback. No signup sent.');
  await browser.close();
})().catch(error => { console.error(error.message); process.exit(1); });
