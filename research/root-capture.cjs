const { chromium } = require('/private/tmp/maychant-visual-review/node_modules/playwright');
const path = require('path');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({ headless: true, channel: 'chrome' });
 const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme:'light' });
 const out=path.join(__dirname,'qa-neighborhood/v6-root');fs.mkdirSync(out,{recursive:true});
 page.setDefaultTimeout(10000);
 page.on('pageerror', e => console.log('PAGEERROR',e.message));
 page.on('console', m => {if(m.type()==='warning'||m.type()==='error')console.log(m.type(),m.text().slice(0,220));});
 await page.goto('http://127.0.0.1:5175', { waitUntil: 'networkidle', timeout:30000 });
 await page.waitForTimeout(1600);
 console.log('ready',await page.locator('#waitlist-form').getAttribute('data-ready'));
 await page.screenshot({path:path.join(out,'root-desktop.png'),timeout:10000});
 await page.locator('.street-footer .motion-toggle').click();
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.waitForTimeout(350);
 await page.screenshot({path:path.join(out,'root-full.png'),fullPage:true,timeout:10000});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo(0,0));
 await page.waitForTimeout(600);
 await page.screenshot({path:path.join(out,'root-phone.png'),timeout:10000});
 await page.screenshot({path:path.join(out,'root-phone-full.png'),fullPage:true,timeout:10000});
 console.log('overflow',await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth));
 await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
